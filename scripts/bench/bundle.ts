// Bundle size of a build and what the JavaScript chunks are made of.
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { TraceMap, eachMapping } from "@jridgewell/trace-mapping";
import { repoPath } from "./profile.ts";

export interface FileSize {
  file: string;
  bytes: number;
  gzip: number;
}

export interface BundleReport {
  /** Everything in the build folder except sourcemaps. */
  totalBytes: number;
  totalGzip: number;
  mapsBytes: number;
  /** JS, CSS, wasm and HTML files, largest first. */
  files: FileSize[];
}

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

export function bundleReport(buildDir: string): BundleReport {
  let totalBytes = 0;
  let totalGzip = 0;
  let mapsBytes = 0;
  const files: FileSize[] = [];
  for (const full of walk(buildDir)) {
    const rel = path.relative(buildDir, full).replace(/\\/g, "/");
    const bytes = fs.statSync(full).size;
    if (rel.endsWith(".map")) {
      mapsBytes += bytes;
      continue;
    }
    const gzip = zlib.gzipSync(fs.readFileSync(full)).length;
    totalBytes += bytes;
    totalGzip += gzip;
    if (/\.(js|mjs|css|wasm|html)$/.test(rel)) files.push({ file: rel, bytes, gzip });
  }
  files.sort((a, b) => b.bytes - a.bytes);
  return { totalBytes, totalGzip, mapsBytes, files };
}

export interface Composition {
  chunk: string;
  bytes: number;
  /** Bytes by source group (a package, or src/ down to two folders), largest first. */
  groups: { group: string; bytes: number; share: number }[];
}

/** The group a source counts under: the npm package, or src/<a>/<b>. */
function groupOf(source: string): string {
  const s = repoPath(source);
  if (s.startsWith("node_modules/")) {
    const parts = s.slice("node_modules/".length).split("/");
    return "npm:" + (parts[0]?.startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0]);
  }
  const parts = s.split("/");
  if (parts[0] === "src") return parts.slice(0, Math.min(3, parts.length - 1)).join("/") || s;
  return s;
}

/**
 * Attributes every generated byte of a chunk to the source its mapping
 * points at (what source-map-explorer does): the bytes from one mapping
 * to the next on a line belong to the first one's source.
 */
export function composition(buildDir: string, chunk: string, top = 25): Composition | null {
  const file = path.join(buildDir, chunk);
  const mapFile = file + ".map";
  if (!fs.existsSync(mapFile)) return null;
  const code = fs.readFileSync(file, "utf8");
  const lines = code.split("\n");
  const map = new TraceMap(fs.readFileSync(mapFile, "utf8"));
  const bytes = new Map<string, number>();
  let prev: { line: number; column: number; group: string } | null = null;
  const add = (group: string, n: number): void => {
    if (n > 0) bytes.set(group, (bytes.get(group) ?? 0) + n);
  };
  const flush = (line: number, column: number): void => {
    if (!prev) return;
    if (prev.line === line) add(prev.group, column - prev.column);
    else add(prev.group, (lines[prev.line - 1]?.length ?? 0) - prev.column);
  };
  eachMapping(map, (m) => {
    flush(m.generatedLine, m.generatedColumn);
    prev = {
      line: m.generatedLine,
      column: m.generatedColumn,
      group: m.source ? groupOf(m.source) : "(unmapped)",
    };
  });
  if (prev) flush(-1, 0);
  const total = Buffer.byteLength(code);
  const mapped = [...bytes.values()].reduce((a, b) => a + b, 0);
  if (total > mapped) bytes.set("(unmapped)", (bytes.get("(unmapped)") ?? 0) + total - mapped);
  return {
    chunk,
    bytes: total,
    groups: [...bytes.entries()]
      .sort((a, b) => b[1] - a[1])
      .slice(0, top)
      .map(([group, n]) => ({ group, bytes: n, share: n / total })),
  };
}
