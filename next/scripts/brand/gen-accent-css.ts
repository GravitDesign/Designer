/**
 * Writes public/brand/accent.light.css and accent.dark.css from the old
 * theme stylesheets (see accent-css.ts):
 *
 *     node scripts/brand/gen-accent-css.ts           # write both files
 *     node scripts/brand/gen-accent-css.ts --check   # fail if they are out of date
 *     node scripts/brand/gen-accent-css.ts --report  # also list the mapped colours
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { accentCss } from "./accent-css.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

export const THEMES = ["light", "dark"] as const;

export function accentFile(theme: string): string {
  return path.join(root, "public", "brand", `accent.${theme}.css`);
}

/**
 * Classes only the dropped cloud, account and purchase UI used (REMOVED.md);
 * the new app never renders them (gen-accent-css.test.ts checks src/).
 */
export const DEAD_CLASSES = [
  "g-cloud-ui-",
  "g-cloud-icon-",
  "g-offline-dialog",
  "g-new-purchase-flow",
];

/** A selector that needs one of DEAD_CLASSES (as a class or in a [class] match). */
export const DEAD_SELECTOR = new RegExp(
  DEAD_CLASSES.map((c) => `\\.${c}|class[*^|~]?="\\s?${c}`).join("|"),
);

export function generate(theme: string): ReturnType<typeof accentCss> {
  const source = fs.readFileSync(
    path.join(root, "public", `designer.browser.${theme}.css`),
    "utf8",
  );
  return accentCss(source, {
    header:
      `/* GravitDesign Next: the old ${theme} theme's pink accent in the brand magenta.\n` +
      `   Generated by scripts/brand/gen-accent-css.ts from designer.browser.${theme}.css;\n` +
      `   don't edit. */\n`,
    dead: DEAD_SELECTOR,
    // public/brand/ is one folder below the old stylesheets.
    urlPrefix: "../",
  });
}

function main(): void {
  const check = process.argv.includes("--check");
  const report = process.argv.includes("--report");
  let stale = false;
  for (const theme of THEMES) {
    const result = generate(theme);
    const file = accentFile(theme);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== result.css) {
        console.error(`${path.relative(root, file)} is out of date`);
        stale = true;
      }
    } else fs.writeFileSync(file, result.css);
    console.log(
      `${theme}: ${result.mapped} declarations mapped, ${result.restated} restated, ` +
        `${(result.css.length / 1024).toFixed(0)} KB`,
    );
    if (report)
      for (const [pair, count] of [...result.colors].sort((a, b) => b[1] - a[1]))
        console.log(`  ${String(count).padStart(4)}  ${pair}`);
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
