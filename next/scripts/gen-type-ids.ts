/**
 * Writes src/engine/core/type-ids.ts from the type ids recorded in the old
 * app (parity/expected/engine-model/type-ids/classes.json).
 *
 *     node scripts/gen-type-ids.ts          # write the file
 *     node scripts/gen-type-ids.ts --check  # fail if it is out of date
 *
 * The recording lists each class under the first G path the harness found
 * it at, walking G's keys in sorted order. Static members were copied to
 * subclasses by GObject.inherit, so a nested class often turns up under a
 * subclass first: GNode.BeforeInsertEvent is recorded as
 * "GAdjustMultiEffect.BeforeInsertEvent". New code registers classes under
 * the path where the old code defined them, so ALIASES maps those defining
 * paths to the recorded ones. They were found by walking every G path in
 * the old app and taking, for each class, the owner whose parent class
 * doesn't have the same member.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "parity/expected/engine-model/type-ids/classes.json");
const target = path.join(root, "src/engine/core/type-ids.ts");

/** Defining path → recorded path, for classes recorded under another path. */
const ALIASES: Record<string, string> = {
  "GBlock.LabelHolder": "GArrowAnnotation.LabelHolder",
  "GElement.Accelerated": "GArrowAnnotation.Accelerated",
  "GElement.Anchor": "GArrowAnnotation.Anchor",
  "GElement.GeometryChangeEvent": "GArrowAnnotation.GeometryChangeEvent",
  "GElement.Layout": "GArrowAnnotation.Layout",
  "GElement.Stylable": "GArrowAnnotation.Stylable",
  "GElement.Transform": "GArrowAnnotation.Transform",
  "GImage.ConvertStatusEvent": "GCollabText.ConvertStatusEvent",
  "GImage.StatusEvent": "GCollabText.StatusEvent",
  "GNode.AfterFlagChangeEvent": "GAdjustMultiEffect.AfterFlagChangeEvent",
  "GNode.AfterInsertEvent": "GAdjustMultiEffect.AfterInsertEvent",
  "GNode.AfterPropertiesChangeEvent": "GAdjustMultiEffect.AfterPropertiesChangeEvent",
  "GNode.AfterRemoveEvent": "GAdjustMultiEffect.AfterRemoveEvent",
  "GNode.AfterRestoreEvent": "GAdjustMultiEffect.AfterRestoreEvent",
  "GNode.AfterSpecialChangeEvent": "GAdjustMultiEffect.AfterSpecialChangeEvent",
  "GNode.BeforeFlagChangeEvent": "GAdjustMultiEffect.BeforeFlagChangeEvent",
  "GNode.BeforeInsertEvent": "GAdjustMultiEffect.BeforeInsertEvent",
  "GNode.BeforePropertiesChangeEvent": "GAdjustMultiEffect.BeforePropertiesChangeEvent",
  "GNode.BeforeRemoveEvent": "GAdjustMultiEffect.BeforeRemoveEvent",
  "GNode.BeforeSpecialChangeEvent": "GAdjustMultiEffect.BeforeSpecialChangeEvent",
  "GNode.Container": "GAdjustMultiEffect.Container",
  "GNode.Identity": "GAdjustMultiEffect.Identity",
  "GNode.MapContainer": "GAdjustMultiEffect.MapContainer",
  "GNode.Multireference": "GAdjustMultiEffect.Multireference",
  "GNode.Properties": "GAdjustMultiEffect.Properties",
  "GNode.Reference": "GAdjustMultiEffect.Reference",
  "GNode.Store": "GAdjustMultiEffect.Store",
  "GPathBase.AnchorPoint": "GArrowAnnotation.AnchorPoint",
  "GPathBase.AnchorPoints": "GArrowAnnotation.AnchorPoints",
  "GStylable.BorderPaintLayer": "GArrowAnnotation.Stylable.BorderPaintLayer",
  "GStylable.Effect": "GArrowAnnotation.Stylable.Effect",
  "GStylable.Effects": "GArrowAnnotation.Stylable.Effects",
  "GStylable.FillPaintLayer": "GArrowAnnotation.Stylable.FillPaintLayer",
  "GStylable.PaintLayer": "GArrowAnnotation.Stylable.PaintLayer",
  "GStylable.PaintLayers": "GArrowAnnotation.Stylable.PaintLayers",
};

function render(ids: Record<string, number>): string {
  const recorded = Object.keys(ids).sort();
  for (const [alias, name] of Object.entries(ALIASES)) {
    if (!(name in ids)) throw new Error(`Alias ${alias} points to ${name}, which is not recorded`);
    if (alias in ids && ids[alias] !== ids[name]) {
      throw new Error(`Alias ${alias} has its own id ${ids[alias]}`);
    }
  }
  const lines = [
    "// Generated by scripts/gen-type-ids.ts from",
    "// parity/expected/engine-model/type-ids/classes.json. Don't edit; rerun the script.",
    "/**",
    " * The old engine's type ids (`__gtype_id__`), by the G path the parity",
    " * harness recorded each class under. Documents save some of them (`_sdf`),",
    " * so registered classes reuse these numbers; see object.ts.",
    " */",
    "export const OLD_TYPE_IDS: Readonly<Record<string, number>> = {",
    ...recorded.map((name) => `  ${JSON.stringify(name)}: ${ids[name]},`),
    "};",
    "",
    "/**",
    " * Where the old code defined a class → the path it was recorded under",
    " * (the recording walks G in sorted order and keeps the first path).",
    " */",
    "export const OLD_TYPE_ID_ALIASES: Readonly<Record<string, string>> = {",
    ...Object.keys(ALIASES)
      .sort()
      .map((alias) => `  ${JSON.stringify(alias)}: ${JSON.stringify(ALIASES[alias])},`),
    "};",
    "",
    "/** The old type id of a class by its old G path, or undefined. */",
    "export function lookupOldTypeId(oldName: string): number | undefined {",
    "  const name = Object.hasOwn(OLD_TYPE_ID_ALIASES, oldName)",
    "    ? (OLD_TYPE_ID_ALIASES[oldName] as string)",
    "    : oldName;",
    "  return Object.hasOwn(OLD_TYPE_IDS, name) ? OLD_TYPE_IDS[name] : undefined;",
    "}",
    "",
  ];
  return lines.join("\n");
}

const ids = JSON.parse(fs.readFileSync(source, "utf8")) as Record<string, number>;
const options = (await prettier.resolveConfig(target)) ?? {};
const output = await prettier.format(render(ids), { ...options, parser: "typescript" });
if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== output) {
    console.error(
      `${path.relative(root, target)} is out of date; run node scripts/gen-type-ids.ts`,
    );
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, output);
  console.log(`Wrote ${path.relative(root, target)} (${Object.keys(ids).length} classes)`);
}
