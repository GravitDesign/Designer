let families: string[] = DEFAULT_FAMILIES.slice();

/** Replaces the list (a copy of `list`, or an empty list). */
export function updateList(list: readonly string[] | null | undefined): void {
  families = (list || []).slice();
}

/** The family from the list that equals `name` ignoring case, or null. */
export function contains(name: string): string | null {
  for (const family of families) {
    if (family.toLowerCase() === name.toLowerCase()) return family;
  }
  return null;
}

/** The current list (for tests and parity hooks). */
export function getList(): readonly string[] {
  return families;
}

/** Restores a list returned by getList without copying it. */
export function setList(list: readonly string[]): void {
  families = list as string[];
}

export const GoogleFontNames = { updateList, contains, getList, setList };
