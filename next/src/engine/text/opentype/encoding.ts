/** Maps a character to a glyph index. */
export interface Encoding {
  charToGlyphIndex(c: string): number | null;
}

/**
 * The encoding of fonts created from scratch: a linear search through the
 * glyphs' unicodes. Returns null when no glyph has the character.
 */
export class DefaultEncoding implements Encoding {
  font: Font;

  constructor(font: Font) {
    this.font = font;
  }

  charToGlyphIndex(c: string): number | null {
    const code = c.codePointAt(0);
    const glyphs = this.font.glyphs;
    if (glyphs) {
      for (let i = 0; i < glyphs.length; i += 1) {
        const glyph = glyphs.get(i) as Glyph;
        for (let j = 0; j < glyph.unicodes.length; j += 1) {
          if (glyph.unicodes[j] === code) {
            return i;
          }
        }
      }
    }
    return null;
  }
}

/** The encoding of parsed fonts: the cmap table. Unmapped characters give 0 (.notdef). */
export class CmapEncoding implements Encoding {
  cmap: CmapTable;

  /** opentype.ts also builds one for a font without a usable cmap (null) before it throws. */
  constructor(cmap: CmapTable | null | undefined) {
    this.cmap = cmap as CmapTable;
  }

  charToGlyphIndex(c: string): number {
    return this.cmap.glyphIndexMap[c.codePointAt(0) as number] || 0;
  }
}

/** A CFF encoding: char code to glyph name, glyph name to index through the charset. */
export class CffEncoding implements Encoding {
  encoding: Record<number, string> | string[];
  charset: string[];

  constructor(encoding: Record<number, string> | string[], charset: string[]) {
    this.encoding = encoding;
    this.charset = charset;
  }

  charToGlyphIndex(s: string): number {
    const code = s.codePointAt(0) as number;
    const charName = (this.encoding as Record<number, string>)[code] as string;
    return this.charset.indexOf(charName);
  }
}

/** Glyph names from the post table. */
export class GlyphNames {
  names: string[];

  constructor(post: PostTable) {
    switch (post.version) {
      case 1:
        this.names = standardNames.slice();
        break;
      case 2: {
        const numberOfGlyphs = post.numberOfGlyphs as number;
        const glyphNameIndex = post.glyphNameIndex as number[];
        const names = post.names as string[];
        this.names = new Array<string>(numberOfGlyphs);
        for (let i = 0; i < numberOfGlyphs; i++) {
          const nameIndex = glyphNameIndex[i] as number;
          if (nameIndex < standardNames.length) {
            this.names[i] = standardNames[nameIndex] as string;
          } else {
            this.names[i] = names[nameIndex - standardNames.length] as string;
          }
        }
        break;
      }
      case 2.5: {
        const numberOfGlyphs = post.numberOfGlyphs as number;
        const glyphNameIndex = post.glyphNameIndex as number[];
        this.names = new Array<string>(numberOfGlyphs);
        for (let i = 0; i < numberOfGlyphs; i++) {
          this.names[i] = standardNames[i + (glyphNameIndex[i] as number)] as string;
        }
        break;
      }
      case 3:
      default:
        this.names = [];
        break;
    }
  }

  nameToGlyphIndex(name: string): number {
    return this.names.indexOf(name);
  }

  glyphIndexToName(gid: number): string {
    return this.names[gid] as string;
  }
}

/**
 * Gives every glyph its unicodes from the cmap and its name from the CFF
 * charset or the post table.
 */
export function addGlyphNames(font: Font): void {
  const glyphIndexMap = (font.tables.cmap as CmapTable).glyphIndexMap;
  const charCodes = Object.keys(glyphIndexMap);

  for (let i = 0; i < charCodes.length; i += 1) {
    const c = charCodes[i] as string;
    const glyphIndex = glyphIndexMap[c as unknown as number] as number;
    const glyph = font.glyphs.get(glyphIndex) as Glyph;
    glyph.addUnicode(parseInt(c));
  }

  for (let i = 0; i < font.glyphs.length; i += 1) {
    const glyph = font.glyphs.get(i) as Glyph;
    if (font.cffEncoding) {
      if (font.isCIDFont) {
        glyph.name = "gid" + i;
      } else {
        glyph.name = (font.cffEncoding as CffEncoding).charset[i] as string;
      }
    } else if (font.glyphNames.names) {
      glyph.name = font.glyphNames.glyphIndexToName(i);
    }
  }
}
