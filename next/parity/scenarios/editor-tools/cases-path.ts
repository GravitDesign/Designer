/** A loop drawn with many small moves. */
const squiggle = (cx: number, cy: number, r: number, turns = 1, n = 24): [number, number][] => {
  const pts: [number, number][] = [];
  for (let i = 1; i <= n; i++) {
    const a = (i / n) * Math.PI * 2 * turns;
    pts.push([Math.round(cx + r * Math.cos(a)), Math.round(cy + r * 0.7 * Math.sin(a))]);
  }
  return pts;
};

